/** Render an icon. `name` falls back to a neutral tag glyph. */
export function icon(name, { size = 20, cls = '', stroke = 1.75, title = '' } = {}) {
  const paths = ICONS[name] || ICONS.tag;
  const body = paths.map((d) => `<path d="${d}"/>`).join('');
  return `<svg class="icon ${cls}" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none"
    stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round"
    aria-hidden="${title ? 'false' : 'true'}" ${title ? `role="img"` : ''}>${title ? `<title>${title}</title>` : ''}${body}</svg>`;
}

